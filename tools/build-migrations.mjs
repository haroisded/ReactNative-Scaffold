// Builds supabase/all-in-one/add.sql and revert.sql out of the individual migration and revert files,
// and checks that every migration has its revert.
//
// The all-in-one files are copies, and copies that nothing checks drift: add a migration, forget the
// paste, and the file someone runs in the SQL Editor quietly stops describing the schema. So they are
// generated and never edited by hand — .claude/instruction_mds/migrations.md.
//
// Node with no dependencies, so it runs anywhere `npm` already does:
//   npm run build:migrations   write both files
//   npm run check:migrations   exit 1 if a revert is missing or either file is stale

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const migrationsDir = join(root, 'supabase', 'migrations');
const revertsDir = join(root, 'supabase', 'reverts');
const outDir = join(root, 'supabase', 'all-in-one');
const check = process.argv.includes('--check');

// A migration that only drops things has nothing to restore, and says so on a line of its own.
const NO_REVERT = /^-- no-revert:/m;

const ADD_HEADER = `-- GENERATED by tools/build-migrations.mjs from supabase/migrations/. Do not edit — run
-- \`npm run build:migrations\` instead (.claude/instruction_mds/migrations.md).
--
-- Every migration, oldest first. Each one is re-runnable, so this whole file can be pasted into the
-- dashboard's SQL Editor to build the schema on a fresh project.
`;

const REVERT_HEADER = `-- GENERATED by tools/build-migrations.mjs from supabase/reverts/. Do not edit — run
-- \`npm run build:migrations\` instead (.claude/instruction_mds/migrations.md).
--
-- DESTROYS DATA. Every revert, newest first, which takes the schema back to nothing. A migration
-- marked \`-- no-revert:\` has no block here.
`;

// Filenames start with a timestamp, so a plain sort is chronological.
function sqlFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.endsWith('.sql'))
    .sort();
}

// A Windows checkout reads CRLF. Normalized so --check compares SQL, not line endings.
function read(dir, name) {
  return readFileSync(join(dir, name), 'utf8').replace(/\r\n/g, '\n');
}

function bundle(header, dir, names) {
  const blocks = names.map((name) => `-- ===== ${name} =====\n\n${read(dir, name).trimEnd()}\n`);
  return `${header}\n${blocks.join('\n\n')}`;
}

const migrations = sqlFiles(migrationsDir);
const reverts = sqlFiles(revertsDir);
const problems = [];

for (const name of migrations) {
  if (!reverts.includes(name) && !NO_REVERT.test(read(migrationsDir, name))) {
    problems.push(`supabase/migrations/${name} has no supabase/reverts/${name} and no "-- no-revert:" line`);
  }
}
for (const name of reverts) {
  if (!migrations.includes(name)) problems.push(`supabase/reverts/${name} matches no migration`);
}

const outputs = [
  ['add.sql', bundle(ADD_HEADER, migrationsDir, migrations)],
  ['revert.sql', bundle(REVERT_HEADER, revertsDir, [...reverts].reverse())],
];

if (check) {
  for (const [name, content] of outputs) {
    if (!existsSync(join(outDir, name)) || read(outDir, name) !== content) {
      problems.push(`supabase/all-in-one/${name} is out of date`);
    }
  }
}

// Refuses to write as well as to pass: an all-in-one file must never ship a migration whose revert is
// missing.
if (problems.length > 0) {
  console.error(`${problems.length} migration problem(s):\n`);
  for (const problem of problems) console.error(`  ${problem}`);
  console.error('\nWrite any missing revert (.claude/instruction_mds/migrations.md), then run `npm run build:migrations`.');
  process.exit(1);
}

if (!check) {
  mkdirSync(outDir, { recursive: true });
  for (const [name, content] of outputs) writeFileSync(join(outDir, name), content);
}

console.log(
  `${migrations.length} migration(s), ${reverts.length} revert(s): all-in-one files ${check ? 'up to date' : 'written'}.`
);
